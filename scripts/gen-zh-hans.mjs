// Writes src/lib/i18n.zh-Hans.ts from the zh-Hant table in src/lib/i18n.ts. Usage: npm run i18n:hans
import { writeFileSync } from 'node:fs';
import { createServer } from 'vite';
import { toHans } from './zh-hans.mjs';

const vite = await createServer({ configFile: false, appType: 'custom', server: { middlewareMode: true, ws: false, watch: null }, optimizeDeps: { noDiscovery: true, include: [] } });
try {
  const { zhHant } = await vite.ssrLoadModule('/src/lib/i18n.ts');
  const lines = Object.entries(zhHant).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(toHans(v))},`);
  writeFileSync(
    new URL('../src/lib/i18n.zh-Hans.ts', import.meta.url),
    `// Generated by \`npm run i18n:hans\` from the zhHant table in i18n.ts. Don't edit by hand: fix the zh-Hant text or the word list in scripts/zh-hans.mjs.\nexport const zhHans: Record<string, string> = {\n${lines.join('\n')}\n};\n`,
  );
  console.log(`Wrote ${lines.length} Simplified Chinese strings.`);
} finally {
  await vite.close();
}
